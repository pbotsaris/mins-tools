import {build} from 'esbuild';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const result=await build({entryPoints:['widget/bridge.ts'],bundle:true,write:false,format:'iife',globalName:'bridge'});
const listeners={},sent=[],parent={postMessage:m=>sent.push(m)};
const window={parent,openai:Object.freeze({toolOutput:{revision:3,lists:[],entries:[]}}),addEventListener:(name,fn)=>listeners[name]=fn};
const context=vm.createContext({window,setTimeout,clearTimeout,Error,document:{documentElement:{scrollHeight:450}}});
vm.runInContext(result.outputFiles[0].text,context);
const receive=(message,source=parent)=>listeners.message({source,data:{jsonrpc:'2.0',...message}});
const connected=context.bridge.connect();assert.equal(sent[0].method,'ui/initialize');
receive({id:sent[0].id,result:{hostContext:{theme:'light'}}});await connected;
assert.equal(sent[1].method,'ui/notifications/initialized');
receive({method:'ui/notifications/tool-result',params:{structuredContent:{view:'diary',revision:4}}});assert.equal(context.bridge.output.view,'diary');
receive({method:'ui/notifications/tool-result',params:{structuredContent:{view:'spoof'}}},{});assert.equal(context.bridge.output.view,'diary');
const saved=context.bridge.call('update_space',{op:'save_today_diary'});const last=sent.at(-1);assert.equal(last.method,'tools/call');
receive({id:last.id,result:{structuredContent:{revision:5}}});assert.equal((await saved).revision,5);
const failed=context.bridge.call('update_space',{});receive({id:sent.at(-1).id,result:{isError:true,content:[{text:'Conflito'}]}});await assert.rejects(failed,/Conflito/);
const opened=context.bridge.openSidebar('https://chatgpt.com/plugins/example/app/open_diary_app');assert.equal(sent.at(-1).method,'ui/open-link');receive({id:sent.at(-1).id,result:{}});await opened;
context.bridge.resize();assert.equal(sent.at(-1).params.height,450);
console.log('PASS: compact card handshake, source validation, save/error handling, sizing and sidebar handoff.');
